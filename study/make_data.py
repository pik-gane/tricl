#!/usr/bin/env python3
"""Data for the study of face-to-face contact dynamics (SocioPatterns high school 2013, Netzschleuder sp_high_school).

Writes study/data/: per day an event file (contacts as establish/terminate events of the symmetric relationship
"meets", in minutes since the start of the day) and a forced-event file (the timetable as links of all students to
hub entities, and the pairs that met on earlier days as links "met before"), plus the entities and static links
used by the model configs (generated by models.py).

Contacts: the sensors record a pair in contact per 20-second interval. Consecutive records with gaps of at most
GAP seconds form one contact. A record at time tau means contact during (tau - 20, tau]; the start and end of a
contact are drawn uniformly within the first and last such interval (fixed seed), which removes ties.
"""
import argparse
import io
import json
import os
import urllib.request
import zipfile

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
URL = "https://networks.skewed.de/net/sp_high_school/files/%s.csv.zip"
HOURS = list(range(8, 17))  # hour hubs h08 ... h16


def fetch(name, raw):
    os.makedirs(raw, exist_ok=True)
    path = os.path.join(raw, name + ".csv.zip")
    if not os.path.exists(path):
        urllib.request.urlretrieve(URL % name, path)
    with zipfile.ZipFile(path) as z:
        edges = pd.read_csv(io.BytesIO(z.read("edges.csv")))
        nodes = pd.read_csv(io.BytesIO(z.read("nodes.csv")))
    edges.columns = [c.strip("# ").strip() for c in edges.columns]
    nodes.columns = [c.strip("# ").strip() for c in nodes.columns]
    return edges, nodes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gap", type=float, default=40.0, help="max. gap (s) within one contact")
    ap.add_argument("--seed", type=int, default=1, help="seed for the jitter of start and end times")
    ap.add_argument("--out", default=os.path.join(HERE, "data"))
    args = ap.parse_args()
    raw = os.path.join(HERE, "data", "raw")
    os.makedirs(args.out, exist_ok=True)
    rng = np.random.default_rng(args.seed)

    prox, nodes = fetch("proximity", raw)
    fb, _ = fetch("facebook", raw)
    survey, _ = fetch("survey", raw)
    label = {int(r["index"]): "s%d" % int(r["id"]) for _, r in nodes.iterrows()}
    cls = {label[int(r["index"])]: "c_" + str(r["class"]).strip().replace("*", "star") for _, r in nodes.iterrows()}

    # contacts:
    e = prox.rename(columns={"source": "s", "target": "t"})
    e["a"] = e[["s", "t"]].min(axis=1)
    e["b"] = e[["s", "t"]].max(axis=1)
    e = e.sort_values(["a", "b", "time"]).reset_index(drop=True)
    d = e.groupby(["a", "b"]).time.diff()
    e["run"] = ((d.isna()) | (d > args.gap)).cumsum()
    runs = e.groupby("run").agg(a=("a", "first"), b=("b", "first"), first=("time", "min"), last=("time", "max"))
    runs["start"] = runs["first"] - 20 * rng.random(len(runs))
    runs["end"] = runs["last"] - 20 * rng.random(len(runs)) + 20
    local = pd.to_datetime(runs["first"], unit="s") + pd.Timedelta(hours=1)  # Marseille, December: UTC+1
    runs["day"] = local.dt.day
    days = sorted(runs.day.unique())
    info = {"gap": args.gap, "seed": args.seed, "days": {}, "students": len(label),
            "classes": sorted(set(cls.values())), "contacts_total": int(len(runs))}

    met_before = set()
    for day in days:
        r = runs[runs.day == day]
        t0_local = pd.Timestamp(2013, 12, int(day), 12 if day == days[0] else 8)
        t0 = (t0_local - pd.Timedelta(hours=1) - pd.Timestamp(1970, 1, 1)).total_seconds()
        t_end = (pd.Timestamp(2013, 12, int(day), 17) - pd.Timedelta(hours=1) - pd.Timestamp(1970, 1, 1)).total_seconds()
        rows = []
        for _, c in r.iterrows():
            s, t = (c.start - t0) / 60, (min(c.end, t_end) - t0) / 60
            s = max(s, 0.0)
            rows.append((s, "establish", label[int(c.a)], label[int(c.b)]))
            if c.end < t_end:
                rows.append((t, "terminate", label[int(c.a)], label[int(c.b)]))
        rows.sort(key=lambda x: x[0])
        with open(os.path.join(args.out, "events_%d.csv" % day), "w") as fh:
            fh.write("t,event,source,relationship,target\n")
            for t, ev, a, b in rows:
                fh.write("%.6f,%s,%s,meets,%s\n" % (t, ev, a, b))
        # forced events: timetable and the pairs that met on earlier days:
        T = (t_end - t0) / 60
        f = []
        for (a, b) in sorted(met_before):
            f.append((0.0, "establish", a, "met before", b))
        start_h = 12 if day == days[0] else 8
        for h in range(start_h, 17):
            tm = (h - start_h) * 60.0
            for st in sorted(label.values()):
                if h > start_h:
                    f.append((tm, "terminate", st, "is in", "h%02d" % (h - 1)))
                f.append((tm, "establish", st, "is in", "h%02d" % h))
                f.append((tm, "establish", st, "is in", "hour change"))
                if h == 10:
                    f.append((tm, "establish", st, "is in", "morning break"))
            for st in sorted(label.values()):
                f.append((tm + 20, "terminate", st, "is in", "hour change"))
                if h == 10:
                    f.append((tm + 20, "terminate", st, "is in", "morning break"))
        f.sort(key=lambda x: x[0])
        with open(os.path.join(args.out, "forced_%d.csv" % day), "w") as fh:
            fh.write("t,event,source,relationship,target\n")
            for t, ev, a, rel, b in f:
                fh.write("%.6f,%s,%s,%s,%s\n" % (t, ev, a, rel, b))
        info["days"][int(day)] = {"T": T, "contacts": int(len(r)), "terminations": int(sum(1 for x in rows if x[1] == "terminate")),
                                  "met_before_pairs": len(met_before)}
        for _, c in r.iterrows():
            met_before.add((label[int(c.a)], label[int(c.b)]))

    # static links:
    static = {"class": [[s, c] for s, c in sorted(cls.items())],
              "facebook": sorted({tuple(sorted((label[int(x.source)], label[int(x.target)]))) for x in fb.itertuples()}),
              "survey": sorted({(label[int(x.source)], label[int(x.target)]) for x in survey.itertuples()})}
    json.dump({"info": info, "static": static, "students": sorted(label.values())}, open(os.path.join(args.out, "data.json"), "w"), indent=1)
    print(json.dumps(info, indent=1))


if __name__ == "__main__":
    main()
